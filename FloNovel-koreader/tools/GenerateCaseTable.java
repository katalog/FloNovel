import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Locale;

/** Pin non-contextual lowercase to the same JDK used by the desktop contract. */
class GenerateCaseTable {
    public static void main(String[] args) throws Exception {
        StringBuilder lower = new StringBuilder("-- Generated by tools/GenerateCaseTable.java with JDK 21.\nreturn { lower = {\n");
        StringBuilder ranges = new StringBuilder("}, assigned = {\n");
        int start = -1;
        for (int cp = 0; cp <= 0x110000; cp++) {
            boolean assigned = cp <= 0x10ffff && !(cp >= 0xd800 && cp <= 0xdfff) && Character.isDefined(cp);
            if (assigned && start < 0) start = cp;
            if (!assigned && start >= 0) {
                ranges.append("{").append(start).append(",").append(cp - 1).append("},\n");
                start = -1;
            }
            if (!assigned) continue;
            String original = new String(Character.toChars(cp));
            String value = original.toLowerCase(Locale.ROOT);
            if (!value.equals(original)) {
                lower.append("[").append(cp).append("] = \"");
                for (byte b : value.getBytes(StandardCharsets.UTF_8)) lower.append(String.format("\\%03d", b & 255));
                lower.append("\",\n");
            }
        }
        Files.writeString(Path.of(args[0]), lower.append(ranges).append("} }\n"), StandardCharsets.UTF_8);
    }
}
